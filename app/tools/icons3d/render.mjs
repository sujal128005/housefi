// Renders the Housefi 3D icons to assets/icons3d/<name>.webp (512 × 512, transparent) and a contact sheet, and the
// looping animations to sprite sheets in assets/anim3d/<name>.webp (320 px frames, row by row) with their manifest
// src/illustrations/anim3dSheets.ts.
// Usage: npm run render            all icons and animations
//        npm run render -- a b c   only these icons / animations
// Needs Chromium for Playwright: npx playwright install chromium
import { chromium } from 'playwright'
import sharp from 'sharp'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { serve } from './serve.mjs'

const OUT = fileURLToPath(new URL('../../assets/icons3d/', import.meta.url))
const SHEET = fileURLToPath(new URL('./preview/', import.meta.url))
const ANIM_OUT = fileURLToPath(new URL('../../assets/anim3d/', import.meta.url))
const MANIFEST = fileURLToPath(new URL('../../src/illustrations/anim3dSheets.ts', import.meta.url))
const CELL = 320
const PORT = 5179

await mkdir(OUT, { recursive: true })
await mkdir(SHEET, { recursive: true })
await mkdir(ANIM_OUT, { recursive: true })
const server = await serve(PORT)
// GPU-less machines (CI, containers) render with SwiftShader.
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 1100 } })
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  await page.goto(`http://127.0.0.1:${PORT}/tools/icons3d/studio.html`)
  await page.waitForFunction(() => window.studioReady === true, null, { timeout: 60000 }).catch(() => {
    throw new Error(`Studio failed to load:\n${errors.join('\n')}`)
  })
  const all = await page.evaluate(() => window.ICON_NAMES)
  const allAnims = await page.evaluate(() => window.ANIM_NAMES)
  const wanted = process.argv.slice(2)
  const names = wanted.length ? all.filter((n) => wanted.includes(n)) : all
  const anims = wanted.length ? allAnims.filter((n) => wanted.includes(n)) : allAnims
  const tiles = []
  for (const name of names) {
    const url = await page.evaluate((n) => window.renderIcon(n), name)
    const png = Buffer.from(url.split(',')[1], 'base64')
    const webp = await sharp(png).resize(512, 512, { kernel: 'lanczos3' }).webp({ quality: 88, alphaQuality: 95, effort: 6 }).toBuffer()
    await writeFile(`${OUT}${name}.webp`, webp)
    tiles.push({ name, png: await sharp(png).resize(192, 192).png().toBuffer() })
    process.stdout.write(`${name} `)
  }
  console.log(`\n${names.length} icons → assets/icons3d/`)

  // Animations: frames rendered at 1024 and scaled down (clean edges), packed row by row.
  for (const name of anims) {
    const { frames, fps } = await page.evaluate((n) => window.startAnim(n), name)
    const cols = frames <= 36 ? 6 : 8
    const rows = Math.ceil(frames / cols)
    const cells = []
    for (let i = 0; i < frames; i++) {
      const url = await page.evaluate((k) => window.animFrame(k), i)
      const input = await sharp(Buffer.from(url.split(',')[1], 'base64')).resize(CELL, CELL, { kernel: 'lanczos3' }).png().toBuffer()
      cells.push({ input, left: (i % cols) * CELL, top: Math.floor(i / cols) * CELL })
    }
    await page.evaluate(() => window.endAnim())
    await sharp({ create: { width: cols * CELL, height: rows * CELL, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
      .composite(cells).webp({ quality: 84, alphaQuality: 90, effort: 6 }).toFile(`${ANIM_OUT}${name}.webp`)
    process.stdout.write(`${name} `)
  }
  if (anims.length) console.log(`\n${anims.length} animations → assets/anim3d/`)

  // The manifest always lists every animation (frames, speed, layout).
  const metas = []
  for (const name of allAnims) {
    const { frames, fps } = await page.evaluate((n) => window.ANIM_META(n), name)
    metas.push(`  ${name.replace(/^anim_/, '')}: { source: require('../../assets/anim3d/${name}.webp'), frames: ${frames}, fps: ${fps}, cols: ${frames <= 36 ? 6 : 8} },`)
  }
  await writeFile(MANIFEST, `// Generated by tools/icons3d/render.mjs; do not edit by hand.\n// Sprite sheets of the looping 3D animations (${CELL} px frames, row by row).\nexport const ANIM_SHEETS = {\n${metas.join('\n')}\n} as const;\n\nexport const ANIM_CELL = ${CELL};\n`)

  // Contact sheet on a light tile background, for review.
  if (tiles.length) {
    const cols = 8
    const cell = 224
    const rows = Math.ceil(tiles.length / cols)
    const label = (t) => Buffer.from(`<svg width="${cell}" height="28"><text x="${cell / 2}" y="20" font-family="Arial" font-size="15" fill="#4E5A77" text-anchor="middle">${t}</text></svg>`)
    const composites = []
    tiles.forEach((t, i) => {
      const x = (i % cols) * cell
      const y = Math.floor(i / cols) * (cell + 28)
      composites.push({ input: t.png, left: x + 16, top: y + 12 }, { input: label(t.name), left: x, top: y + cell - 4 })
    })
    await sharp({ create: { width: cols * cell, height: rows * (cell + 28), channels: 4, background: '#EEF2FB' } }).composite(composites).png().toFile(`${SHEET}sheet${wanted.length ? '-partial' : ''}.png`)
  }
  if (errors.length) console.warn(errors.join('\n'))
} finally {
  await browser.close()
  server.close()
}
